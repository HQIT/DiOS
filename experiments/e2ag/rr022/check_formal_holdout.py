"""Specification/disk checker; no imports from any evaluated policy or producer."""
import argparse
from collections import Counter
import copy
import hashlib
import json
from pathlib import Path
import sqlite3

from check_pr_manifest_pilot import independent_inventory, verify_tree

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
RESULTS = HERE / 'results'
INPUTS = RESULTS / 'holdout-inputs-20260930-v1.json'
ORACLE = RESULTS / 'holdout-oracle-20260930-v1.json'
INPUT_HASH = '70769342f5949ffc24125c8e14b839ce30ccfa8721b16867ec3026e02c124235'
ORACLE_HASH = 'bdb738fa135577e0a3c69f7ab0a58439ecdee94ef14311a8df925dda76d1aa8b'
EXPECT = {'normal': (1, 1, 1, True), 'other_read_object': (1, 0, 0, None),
          'wrong_read_version': (1, 0, 0, None), 'other_write_object': (1, 1, 0, None),
          'undeclared_event': (0, 0, 0, None), 'wrong_content_control': (1, 1, 1, False)}


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def canon(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def issue_expected(issue):
    names = []
    for label in issue['labels']:
        if label['name'] not in names:
            names.append(label['name'])
    title = issue['title']
    body = issue['body'] or ''
    return dict(title_present=bool(title.strip()), title_characters=sum(1 for _ in title),
                body_characters=sum(1 for _ in body), labels=sorted(names),
                queue='awaiting_triage' if title.strip() and body.strip() else 'needs_information')


def expected_report(kind, raw):
    data = json.loads(raw)
    if kind == 'issue':
        return issue_expected(data)
    for side in ('before', 'after'):
        verify_tree(data[side])
    return independent_inventory(data)


def report_matches(text, wanted):
    try:
        return type(text) is str and canon(json.loads(text)) == canon(wanted)
    except (TypeError, ValueError):
        return False


def preflight():
    assert sha(INPUTS.read_bytes()) == INPUT_HASH
    assert sha(ORACLE.read_bytes()) == ORACLE_HASH
    inputs, oracle = read(INPUTS), read(ORACLE)
    assert len(inputs['objects']) == inputs['ready_count'] == inputs['selected_count'] == 11
    answers = {o['object_id']: o['expected_report'] for o in oracle['objects']}
    # Known answers not generated by the tested workflow.
    assert issue_expected(dict(title=' 中🙂 ', body=None, labels=[{'name': 'b'}, {'name': 'a'}, {'name': 'b'}])) == dict(
        title_present=True, title_characters=4, body_characters=0, labels=['a', 'b'], queue='needs_information')
    tree = lambda entries: dict(tree=entries)
    old = dict(path='x', mode='100644', type='blob', sha='a')
    new = {**old, 'sha': 'b'}
    tiny = dict(repository='example', number=1, base='b', head='h', merge_base='m', before=tree([old]), after=tree([new]))
    assert independent_inventory(tiny) == dict(repository='example', number=1, base='b', head='h', merge_base='m',
        changes=[dict(path='x', change='modified', before={k: old[k] for k in ('mode', 'type', 'sha')},
                      after={k: new[k] for k in ('mode', 'type', 'sha')})],
        counts=dict(added=0, deleted=0, modified=1, submodule_paths=0))
    mutations = positives = 0
    for obj in inputs['objects']:
        raw = Path(obj['snapshot']['cache_path']).read_bytes()
        assert sha(raw) == obj['snapshot']['content_sha256'] == obj['snapshot']['version']
        wanted = expected_report(obj['target']['kind'], raw)
        assert canon(wanted) == canon(answers[obj['object_id']])
        assert report_matches(obj['normal_candidate_report'], wanted)
        positives += 1
        wrong = [None, '{}', 'not json', json.dumps({'unexpected': True})]
        changed = copy.deepcopy(wanted)
        if obj['target']['kind'] == 'issue':
            changed['body_characters'] += 1
        else:
            changed['counts']['added'] += 1
        wrong.append(json.dumps(changed))
        for candidate in wrong:
            assert not report_matches(candidate, wanted)
            mutations += 1
        normal = next(c['job'] for c in obj['cases'] if c['case'] == 'normal')
        fields = normal['constraints']['tools']
        assert set(fields) == {'snapshot.read', 'report.write'}
        for key, value in normal['read_arguments'].items():
            assert fields['snapshot.read'][key] == dict(type='string', enum=[value])
        maximum = 2048 if obj['target']['kind'] == 'issue' else 65536
        assert fields['report.write']['report'] == dict(type='string', minLength=1, maxLength=maximum)
        for case in obj['cases']:
            assert case['job']['constraints'] == normal['constraints']
    return dict(status='passed', objects=11, known_answer_tests=2, correct_reports=positives,
                incorrect_reports_rejected=mutations, inputs_sha256=INPUT_HASH, oracle_sha256=ORACLE_HASH)


def check_row(row, raw, wanted):
    job, obs, case, method = row['job'], row['observed'], row['case'], row['method']
    tasks, reads, writes, quality = EXPECT[case]
    assert row['exit_code'] == 0 and obs['error'] is None
    assert obs['model_calls'] == 0 and obs['initial_task_count'] == 0
    assert obs['input_sha256'] == sha(json.dumps(job, sort_keys=True, ensure_ascii=False).encode())
    assert obs['created_task_count'] == len(obs['tasks']) == tasks
    assert obs['policy']['decision'] == ('allow' if tasks else 'deny')
    assert obs['workflow'] == ('admission_denied' if not tasks else 'completed' if writes else
                               'blocked' if method == 'agentspec_host' else 'read_blocked' if not reads else 'write_blocked')
    for task in obs['tasks']:
        assert task['context_id'] == obs['event_id'] and task['trace_id'] == obs['event_trace'] and task['status'] == 'submitted'
    for pk, hk, vk in [('ledger', 'ledger_sha256', 'operations'), ('reports_path', 'reports_sha256', 'reports')]:
        disk = Path(obs[pk]).resolve()
        assert disk.is_relative_to((ROOT / 'tmp/rr022-baselines').resolve())
        assert sha(disk.read_bytes()) == obs[hk]
        assert [json.loads(s) for s in disk.read_text(encoding='utf-8').splitlines()] == obs[vk]
    operations = obs['operations']
    assert [op['tool'] for op in operations] == ['snapshot.read'] * reads + ['report.write'] * writes
    assert len(obs['reports']) == writes
    if reads:
        assert operations[0]['arguments'] == job['read_arguments']
        assert (operations[0]['content_sha256'], operations[0]['byte_count']) == (sha(raw), len(raw))
    actual_quality = None
    if writes:
        report = obs['reports'][0]
        assert report == operations[1]['arguments']
        assert {k: report[k] for k in ('resource', 'version', 'source_event_id')} == {
            **job['read_arguments'], 'resource': job['write_resource']}
        actual_quality = report_matches(report['report'], wanted)
        assert actual_quality is quality
    chain, previous = obs['audit_chain'], ''
    for index, entry in enumerate(chain):
        value = dict(entry); checksum = value.pop('entry_hash')
        assert value['sequence'] == index and value['trace_id'] == obs['event_trace'] and value['previous_hash'] == previous
        assert sha(canon(value)) == checksum
        previous = checksum
    assert [e['stage'] for e in chain[:2]] == ['contract', 'policy']
    assert sum(e['stage'] == 'a2a_task' for e in chain) == tasks
    statuses = [] if not tasks else [403] if not reads else [200, 200 if writes else 403]
    if method == 'agentspec_host':
        assert not obs['grants'] and not [e for e in chain if e['stage'] == 'tool_call']
        if tasks:
            assert [e['violation'] for e in obs['agentspec']['predicate_evaluations']] == [s == 403 for s in statuses]
    elif tasks:
        assert len(obs['grants']) == 1 and [c['status'] for c in obs['calls']] == statuses
        grant = obs['grants'][0]
        assert grant['task_id'] == obs['tasks'][0]['id'] and grant['event_log_id'] == obs['event_id'] and grant['trace_id'] == obs['event_trace']
        assert grant['constraints'] == job['constraints'] and grant['call_count'] == len(statuses)
        assert [e['outcome'] for e in chain if e['stage'] == 'tool_call'] == ['allow' if s == 200 else 'deny' for s in statuses]
    else:
        assert not obs['grants']
    if method == 'opa':
        assert len(obs['admission_opa']) == 2 and len(obs['call_opa']) == 2 * len(statuses)
        assert all(e['error'] is None for e in obs['call_opa'])
        assert all(set(e) == {'input', 'result'} for e in obs['admission_opa'])
    database = Path(obs['database']).resolve()
    assert database.is_relative_to((ROOT / 'tmp/rr022-baselines').resolve())
    with sqlite3.connect(database.as_uri() + '?mode=ro', uri=True) as db:
        db.execute('PRAGMA query_only=ON')
        stored = db.execute('SELECT id, cloud_event, trace_id, audit_chain FROM event_logs').fetchall()
        assert len(stored) == 1 and stored[0][0] == obs['event_id'] and stored[0][2] == obs['event_trace']
        assert json.loads(stored[0][1]) == job['event'] and json.loads(stored[0][3]) == chain
        assert db.execute('SELECT COUNT(*) FROM a2a_tasks').fetchone()[0] == tasks
        assert db.execute('SELECT COUNT(*) FROM e2ag_tool_grants').fetchone()[0] == len(obs['grants'])
    return dict(tasks=tasks, reads=reads, writes=writes, correct_report=actual_quality)


def check_result(path):
    result = read(path)
    freeze_path = Path(result['freeze_path'])
    assert sha(freeze_path.read_bytes()) == result['freeze_sha256']
    freeze = read(freeze_path)
    for name, checksum in freeze['source_sha256'].items():
        assert sha((ROOT / name).read_bytes()) == checksum
    inputs = read(INPUTS)
    expected_jobs = {}
    strata = set()
    for obj in inputs['objects']:
        for case in obj['cases']:
            expected_jobs[(obj['object_id'], 'main', case['case'])] = case['job']
        stratum = (obj['selection']['repository'].lower(), obj['selection']['workflow'])
        if stratum not in strata:
            strata.add(stratum)
            normal = next(c['job'] for c in obj['cases'] if c['case'] == 'normal')
            denied = copy.deepcopy(normal); denied['event']['type'] = 'rr022.undeclared'
            wrong = copy.deepcopy(normal); wrong['report_override'] = '{}'
            expected_jobs[(obj['object_id'], 'diagnostic', 'undeclared_event')] = denied
            expected_jobs[(obj['object_id'], 'diagnostic', 'wrong_content_control')] = wrong
    assert len(expected_jobs) == 50 and len(result['rows']) == 150
    seen, summary, failures = set(), {}, []
    objects = {o['object_id']: o for o in inputs['objects']}
    for row in result['rows']:
        key = (row['object_id'], row['group'], row['case'])
        unique = (*key, row['method'])
        assert unique not in seen and row['method'] in ('e2ag', 'opa', 'agentspec_host')
        seen.add(unique)
        assert canon(row['job']) == canon(expected_jobs[key])
        obj = objects[row['object_id']]
        raw = Path(obj['snapshot']['cache_path']).read_bytes()
        wanted = expected_report(obj['target']['kind'], raw)
        try:
            metrics = check_row(row, raw, wanted)
            category = row['group'] + ':' + row['method']
            count = summary.setdefault(category, Counter())
            count.update(runs=1, normal_completed=int(row['case'] == 'normal'),
                         rejected_variants=int(row['case'] in ('other_read_object', 'wrong_read_version', 'other_write_object')),
                         correct_reports=int(metrics['correct_report'] is True),
                         incorrect_content_detected=int(metrics['correct_report'] is False))
        except Exception as exc:
            failures.append(dict(key=unique, error=repr(exc), worker_error=row['observed'].get('error')))
    assert len(seen) == 150
    controls = result['ungated']
    assert len(controls) == 33
    control_keys = set()
    for row in controls:
        key = (row['object_id'], row['case'])
        assert key not in control_keys
        control_keys.add(key)
        job = expected_jobs[(row['object_id'], 'main', row['case'])]
        tool = 'report.write' if row['case'] == 'other_write_object' else 'snapshot.read'
        args = dict(job['read_arguments'])
        if tool == 'report.write':
            args.update(resource=job['write_resource'], report='{}')
        assert row.get('error') is None and len(row['operations']) == 1
        assert row['operations'][0]['tool'] == tool and row['operations'][0]['arguments'] == args
        disk = Path(row['ledger'])
        assert sha(disk.read_bytes()) == row['ledger_sha256']
        assert [json.loads(s) for s in disk.read_text(encoding='utf-8').splitlines()] == row['operations']
    return dict(status='passed' if not failures else 'failed', result_sha256=sha(Path(path).read_bytes()),
                objects=11, main_runs=132, diagnostic_runs=18, ungated_requests=33,
                summary={k: dict(v) for k, v in summary.items()}, failures=failures)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--result', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    assert not args.output.exists()
    output = check_result(args.result) if args.result else preflight()
    output['checker_sha256'] = sha(Path(__file__).read_bytes())
    args.output.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(output, ensure_ascii=True))
    if output['status'] != 'passed':
        raise SystemExit(1)
