import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {chromium} from '../node_modules/playwright/index.mjs';
const root=process.argv[2];
const fixture=JSON.parse(await fs.readFile(root+'/ready.json','utf8'));
const browser=await chromium.launch({headless:true});
const checks=[],errors=[];
try {
  const context=await browser.newContext({locale:'zh-CN',viewport:{width:1440,height:1000}});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:13347/dios/#console/tasks/'+fixture.run_id);
  await page.getByPlaceholder('Access Token',{exact:true}).fill('operator-test');
  await page.getByRole('button',{name:'进入',exact:true}).click();
  const selector=page.getByRole('combobox',{name:/执行 Agent/});
  await selector.selectOption('review');
  assert.equal(await page.getByText(/执行要求：原生网络关闭/).count(),0);
  checks.push('legacy-profile-no-isolation-claim');
  await selector.selectOption('strict');
  await page.getByText('执行要求：原生网络关闭、工作区只读；外部工具经授权通道调用。',{exact:true}).waitFor();
  checks.push('strict-profile-declaration');
  await page.screenshot({path:root+'/isolation-zh.png',fullPage:true});
  await page.getByLabel('语言',{exact:true}).selectOption('en');
  await page.getByText('Execution requires native networking disabled and a read-only workspace. External tools use the authorized channel.',{exact:true}).waitFor();
  checks.push('english');
  await page.getByLabel('Theme',{exact:true}).selectOption('dark');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  checks.push('dark-mobile');
  await page.screenshot({path:root+'/isolation-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await fs.writeFile(root+'/browser.json',JSON.stringify({passed:true,checks,page_errors:errors},null,2)+'\n');
  console.log(JSON.stringify({passed:true,checks:checks.length}));
} finally {await browser.close();}
