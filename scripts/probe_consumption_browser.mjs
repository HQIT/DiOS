import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {chromium} from '../node_modules/playwright/index.mjs';
const root=process.argv[2];
const ids=JSON.parse(await fs.readFile(root+'/ready.json','utf8'));
const browser=await chromium.launch({headless:true});
const checks=[];const errors=[];
try {
  const context=await browser.newContext({locale:'zh-CN',colorScheme:'light',viewport:{width:1440,height:1100}});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  const route=id=>'http://127.0.0.1:13345/dios/#console/tasks/'+id;
  await page.goto(route(ids.settled));
  await page.getByPlaceholder('Access Token',{exact:true}).fill('operator-test');
  await page.getByRole('button',{name:'进入',exact:true}).click();
  let panel=page.getByRole('region',{name:'用量预算与结算',exact:true});
  await panel.waitFor();
  assert.match(await panel.innerText(),/预留: 3 · 结算: 1/);checks.push('real-api-settlement-visible');
  await page.goto(route(ids.unreconciled));
  await page.waitForFunction(()=>document.querySelector('[aria-label="用量预算与结算"]')?.textContent.includes('待对账'));
  checks.push('uncertain-cost-retained');
  await page.goto(route(ids.blocked));
  await panel.getByText('当前通道不支持费用硬上限，任务暂不派发。',{exact:true}).waitFor();
  await panel.getByText('预留预算不足，等待结算或调整额度。',{exact:true}).waitFor();
  await page.getByText('预算准入未通过，任务尚未派发。',{exact:true}).waitFor();
  checks.push('unsupported-cap-blocked','budget-exhaustion-visible');
  await panel.scrollIntoViewIfNeeded();await page.screenshot({path:root+'/budget-zh.png',fullPage:true});
  await page.getByLabel('语言',{exact:true}).selectOption('en');
  panel=page.getByRole('region',{name:'Usage budget and settlement',exact:true});
  await panel.getByText('This channel cannot enforce a cost ceiling. Dispatch is blocked.',{exact:true}).waitFor();
  await page.getByLabel('Theme',{exact:true}).selectOption('dark');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');checks.push('english-dark');
  await page.setViewportSize({width:390,height:844});
  await panel.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);checks.push('mobile-layout');
  await page.screenshot({path:root+'/budget-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await fs.writeFile(root+'/browser.json',JSON.stringify({passed:true,checks,page_errors:errors},null,2)+'\n');
  console.log(JSON.stringify({passed:true,checks:checks.length}));
} finally {await browser.close();}
